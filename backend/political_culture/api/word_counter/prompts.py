TEXT_INFO_EXTRACTION_PROMPT = (
    "You are an information-extraction agent. You will receive a document: the whole"
    " text or, for a long one, its opening followed by a few passages from the rest,"
    " separated by [...]."
    "\n1. Identify the **title** and the **author**, without extra info. Leave them"
    " null when the text doesn't state them."
    "\n2. Write a concise yet information-rich summary that lets another LLM"
    " understand the document without reading it. Cover:"
    "\n   • Main topic or theme"
    "\n   • Content overview (key arguments, events, ideas)"
    "\n   • Genre (fiction, scientific article, legal contract, …)"
    "\n   • Explicit and implicit entities (people, organisations, places, concepts)"
    "\n   • Tone, intent and style"
    "\n   • Domain-specific context or prior knowledge assumed by the text"
    "\n   • Notable structure (chapters, dialogue, citations, …)"
)


WORD_EXTRACTION_PROMPT = (
    "You will receive two inputs:"
    "\n1. A context summary describing the content, topic, genre, entities, tone,"
    " and structure of a document."
    "\n2. A list of words extracted from the document, each with its frequency of"
    " occurrence."
    "\n\nYour task is to identify and return only the words that are contextually"
    " relevant to the document, based on the information provided in the summary."
    "\n\nContextually relevant words are those that:"
    "\n1) Relate directly to the main topic, subject matter, or themes."
    "\n2) Represent key entities, concepts, or domain-specific terminology."
    "\n3) Are important for understanding the content, structure, or intent of the"
    " document."
    "\n4) May include uncommon or high-signal terms, even if they are low in"
    " frequency."
    "\nDo not return general-purpose or filler words (e.g., 'the', 'also', 'very')"
    " unless they carry domain-specific importance."
    "\nDo not rely solely on frequency — use the summary to infer what matters."
)
